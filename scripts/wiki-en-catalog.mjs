#!/usr/bin/env node
// Regenerates WIKI_EN_SHARDS in src/rag/wikiEnPacks.ts (between the "generated"
// markers) from the shard packs' .json summaries, so sizes, SHA-256 and counts
// in the catalog are the measured ones. Each shard's URL is pinned to the
// dataset commit it was uploaded in.
//
//   node scripts/wiki-en-catalog.mjs packs/ 00-07=6e9afe9658e0f933a36f233749f51967dd57fbe0 08-14=ce244fa65789d8628de0d979969b7d526f10d63f
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const TARGET = "src/rag/wikiEnPacks.ts";
const REPO = "https://huggingface.co/datasets/r4topunk/boar-packs/resolve";
const [dir, ...ranges] = process.argv.slice(2);
if (!dir || !ranges.length) throw new Error("usage: wiki-en-catalog.mjs <packs dir> <from-to=commit>...");

const commitOf = new Map();
for (const r of ranges) {
  const m = r.match(/^(\d+)-(\d+)=([0-9a-f]{40})$/);
  if (!m) throw new Error(`bad range "${r}"`);
  for (let n = Number(m[1]); n <= Number(m[2]); n++) commitOf.set(n, m[3]);
}
const shards = [...commitOf.keys()].sort((a, b) => a - b).map((n) => {
  const nn = String(n).padStart(2, "0");
  const name = `boar-wiki-en-${nn}.sqlite`;
  const s = JSON.parse(readFileSync(join(dir, `${name}.json`), "utf8"));
  return {
    part: n,
    sizeBytes: s.sizeBytes,
    sha256: s.sha256,
    sourceUrl: `${REPO}/${commitOf.get(n)}/wiki/en/${name}`,
    articles: s.articles,
  };
});
const body = JSON.stringify(shards, null, 2).replace(/"([a-zA-Z0-9]+)":/g, "$1:");
const src = readFileSync(TARGET, "utf8");
const start = "// <generated by scripts/wiki-en-catalog.mjs>";
const end = "// </generated>";
const a = src.indexOf(start);
const b = src.indexOf(end);
if (a < 0 || b < 0) throw new Error(`markers not found in ${TARGET}`);
writeFileSync(TARGET, `${src.slice(0, a + start.length)}\nexport const WIKI_EN_SHARDS: WikiEnShard[] = ${body};\n${src.slice(b)}`);
console.log(`${shards.length} shards written to ${TARGET}`);
